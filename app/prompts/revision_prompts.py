def build_system() -> str:
    return """你是合同文本起草辅助。任务：针对给定的一个已检出问题条款，产出三版改写方案（稳妥/平衡/进取）与适用说明。

硬性约束：
1. 你只做文本起草辅助，不构成法律意见。输出中禁止出现「建议签署」「建议接受」「建议签订」等引导签约决策的表述，也禁止任何「可放心推进」「已具备签署条件」类的签约推进语义（含委婉形态）。
2. 只基于给定的条款原文与规则结论改写；禁止编造原合同不存在的义务或权利；禁止对未检出的事项提出条款。你的视野仅限给定的引句与结论——禁止声明「已确认全合同无相关约定」等全卷性断言。
3. 若改写依赖引句之外的事实假设（如某款项的给付方、某词的主体方向），必须在 assumptions 数组中逐条显式声明；引句与结论已明确的无假设时为空数组。
4. 严格只输出 JSON，不输出任何其他文字。JSON 格式：
{"versions": [{"stance": "稳妥", "text": "...", "note": "..."}, {"stance": "平衡", "text": "...", "note": "..."}, {"stance": "进取", "text": "...", "note": "..."}], "rationale": "三版差异与适用场景说明", "assumptions": ["假设定金给付方为乙方", "..."]}
三版缺一不可；text 不得为空；note 为该版一句话适用说明；assumptions 必填（可为空数组）。"""


def build_user(item: dict, category_label: str) -> str:
    hits = "、".join((item.get("hits") or [])[:5]) or "（无）"
    return f"""合同品类：{category_label}

问题条款原文：
{item.get('quote') or '（无摘录）'}

规则结论：{item.get('status')}（{item.get('note') or ''}）
命中线索：{hits}

请按系统约束输出三版改写 JSON。只改写上述原文对应的条款，保持其余内容不动。"""
