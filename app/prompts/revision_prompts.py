# -*- coding: utf-8 -*-
"""M7 修改建议提示词（B7-1，铁律：AI 不改判定、只出起草参考）。

红线（老钱终裁 final-ruling-20261024.md）：
1. 生成物=文本起草辅助，非法律意见；禁「建议签署/接受」类表述（禁语过滤+逐例核对）；
2. 只基于给定 item 原文与结论，禁止对未检出域生成进攻性条款；
3. 三层留痕（原引句+修改文本+理由）由服务层落库，模型只产出内容。
"""
from __future__ import annotations

PROMPT_VERSION = "rev-v1"

# 固定声明文案（应用侧拼接，不来自模型——保证每条建议必然携带）
DECLARATION = "以下为文本起草辅助参考，不构成法律意见；是否采纳由您自行判断，重要事项请咨询专业律师。"

# 禁语（正则片段，命中即整项降级——第一道机械防线，逐例语义核对为验收本体）
BANNED_PATTERNS = (
    "建议签署",
    "建议接受",
    "建议签订",
    "应当签署",
    "建议采纳",
    "可直接签署",
)


def build_system() -> str:
    return """你是合同文本起草辅助。任务：针对给定的一个已检出问题条款，产出三版改写方案（稳妥/平衡/进取）与适用说明。

硬性约束：
1. 你只做文本起草辅助，不构成法律意见。输出中禁止出现「建议签署」「建议接受」「建议签订」等引导签约决策的表述。
2. 只基于给定的条款原文与规则结论改写；禁止编造原合同不存在的义务或权利；禁止对未检出的事项提出条款。
3. 严格只输出 JSON，不输出任何其他文字。JSON 格式：
{"versions": [{"stance": "稳妥", "text": "...", "note": "..."}, {"stance": "平衡", "text": "...", "note": "..."}, {"stance": "进取", "text": "...", "note": "..."}], "rationale": "三版差异与适用场景说明"}
三版缺一不可；text 不得为空；note 为该版一句话适用说明。"""


def build_user(item: dict, category_label: str) -> str:
    hits = "、".join((item.get("hits") or [])[:5]) or "（无）"
    return f"""合同品类：{category_label}

问题条款原文：
{item.get('quote') or '（无摘录）'}

规则结论：{item.get('status')}（{item.get('note') or ''}）
命中线索：{hits}

请按系统约束输出三版改写 JSON。只改写上述原文对应的条款，保持其余内容不动。"""
